from dataclasses import dataclass, field
from typing import List, Optional


@dataclass
class SheetSpec:
    """单个工作表的校验规范"""
    headers: List[str]          # 期望的文本字段名列表
    description: str            # 说明
    category: str               # 类别
    numeric_cols: Optional[int] = None    # 期望的数值列数量（None=不校验）
    contract_cols: bool = False           # 是否有合同组列
    sum_to_one: bool = False              # 模式类工作表：60列数值每行之和必须等于1


